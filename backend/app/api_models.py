import uuid
from datetime import datetime
from typing import Annotated, List, Optional

from pydantic import BaseModel, ConfigDict, StringConstraints


class ActClaim(BaseModel):
    sub: str  # Email address of the impersonating WorkOS Dashboard user


class AccessTokenJWT(BaseModel):
    iss: str  # Issuer
    sub: str  # Unique ID of the user
    act: Optional[ActClaim] = None  # RFC 8693 impersonation claim

    # This app has no organizations, so org-scoped claims are optional and unused.
    org_id: Optional[str] = None
    role: Optional[str] = None
    roles: Optional[List[str]] = None
    permissions: Optional[List[str]] = None
    entitlements: Optional[List[str]] = None

    sid: str  # Session ID
    jti: str  # Token ID

    exp: datetime  # Expiration (epoch seconds)
    iat: datetime  # Issued-at (epoch seconds)


class AuthenticatedUser(BaseModel):
    user_id: str
    session_id: str


class MeResponse(BaseModel):
    user_id: str


class CodebaseResponse(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    name: str
    created_at: datetime


class CreateCodebaseRequest(BaseModel):
    """Sent by the frontend's Vercel Blob upload callback once a codebase zip has been uploaded."""

    # Generated by the uploading browser so it can poll GET /api/codebases/{id} for the new row.
    id: uuid.UUID
    user_id: Annotated[str, StringConstraints(min_length=1, max_length=255)]
    name: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=255)
    ]
    blob_uri: Annotated[str, StringConstraints(min_length=1)]
