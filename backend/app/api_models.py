# --- Agent-generated assessments ---------------------------------------------------------------
# `GeneratedAssessment` is both the `outputSchema` sent to the eve agent (as JSON Schema, see
# app/agent.py) and the validator for the result it returns, so the two can't drift apart.

NonEmptyStr = Annotated[str, StringConstraints(strip_whitespace=True, min_length=1)]


class GeneratedConcept(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=255)
    ] = Field(description="Short, specific name for a system or concept in this codebase.")


class GeneratedContributor(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=255)
    ] = Field(description="Author name, exactly as list_git_contributors returned it.")
    email: Annotated[
        str,
        StringConstraints(
            strip_whitespace=True, to_lower=True, min_length=3, max_length=320
        ),
    ] = Field(description="Author email, exactly as list_git_contributors returned it.")


class GeneratedQuestion(BaseModel):
    model_config = ConfigDict(extra="forbid")

    concept: NonEmptyStr = Field(
        description="The exact `name` of the concept this question tests."
    )
    question: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=2000)
    ]
    choices: Annotated[
        list[Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=1000)]],
        Field(min_length=4, max_length=4),
    ] = Field(description="Exactly four answer options, only one of them correct.")
    correct_index: Annotated[int, Field(ge=0, le=3)] = Field(
        description="0-based index into `choices` of the single correct option."
    )

    @model_validator(mode="after")
    def choices_are_distinct(self) -> "GeneratedQuestion":
        if len({choice.casefold() for choice in self.choices}) != len(self.choices):
            raise ValueError("A question's four choices must be distinct")
        return self


class GeneratedAssessment(BaseModel):
    model_config = ConfigDict(extra="forbid")

    # First, so the model decides whether to reject before it writes an assessment. Without it the
    # schema's required concepts and questions push the model into assessing whatever it was given
    # (e.g. a zip of images), since eve fails a turn that ends without a schema-matching result.
    # A required boolean, because the model filled an optional reason with "null" for real
    # codebases; rejection_reason is only read when this is true.
    rejected: bool = Field(
        description=(
            "true only when the upload has no source code to assess, such as a zip of only "
            "images, documents, or data files; false for a real codebase."
        )
    )
    rejection_reason: str | None = Field(
        default=None,
        max_length=1000,
        description=(
            "When rejected is true, one plain-language sentence saying what the upload contains "
            "instead of source code. Ignored when rejected is false."
        ),
    )
    # Minimums for a real assessment are enforced in validate_assessment, not here, so that a
    # rejection can leave these empty.
    concepts: Annotated[list[GeneratedConcept], Field(max_length=10)] = Field(
        description=(
            "The most important concepts and systems in the codebase, 1 to 10. Empty when "
            "rejected is true."
        )
    )
    contributors: list[GeneratedContributor] = Field(
        description="Commit authors from the git history; empty when there is no .git directory."
    )
    questions: Annotated[list[GeneratedQuestion], Field(max_length=30)] = Field(
        description="Multiple-choice questions, 2-3 per concept. Empty when rejected is true."
    )

    @model_validator(mode="after")
    def validate_assessment(self) -> "GeneratedAssessment":
        if self.rejected:
            # A rejection carries no assessment; anything else the agent sent is ignored.
            return self
        if not self.concepts:
            raise ValueError("An assessment needs at least one concept")
        if not self.questions:
            raise ValueError("An assessment needs at least one question")
        names = [concept.name for concept in self.concepts]
        if len(set(names)) != len(names):
            raise ValueError("Concept names must be unique")
        unknown = {q.concept for q in self.questions} - set(names)
        if unknown:
            raise ValueError(f"Questions reference unknown concepts: {sorted(unknown)}")
        return self


class AssessmentWebhookCompleted(BaseModel):
    status: Literal["completed"]
    session_id: str
    # Validated as GeneratedAssessment in the handler, so an invalid result can be recorded as a
    # failed assessment instead of only being rejected.
    result: dict[str, Any]


class AssessmentWebhookFailed(BaseModel):
    status: Literal["failed"]
    session_id: str
    error: str


# Sent by the eve agent's assessment-webhook hook when its turn settles.
AssessmentWebhook = Annotated[
    AssessmentWebhookCompleted | AssessmentWebhookFailed, Field(discriminator="status")
]


# --- Taking an assessment ----------------------------------------------------------------------
# Public: anyone with an assessment's link can take it, so these models never expose correct
# answers or anything about the codebase beyond its name.


class AssessmentQuestion(BaseModel):
    id: uuid.UUID
    concept: str
    question: str
    choices: list[str]


class AssessmentContributorOption(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    name: str
    email: str


class TakeAssessmentResponse(BaseModel):
    id: uuid.UUID
    codebase_name: str
    questions: list[AssessmentQuestion]
    # The codebase's known contributors, for the "who are you?" dropdown.
    contributors: list[AssessmentContributorOption]


class ExistingContributorIdentity(BaseModel):
    kind: Literal["existing"]
    contributor_id: uuid.UUID


class NewContributorIdentity(BaseModel):
    """A contributor who isn't in the codebase's list (e.g. no commits in the uploaded history)."""

    kind: Literal["new"]
    name: Annotated[
        str, StringConstraints(strip_whitespace=True, min_length=1, max_length=255)
    ]
    email: Annotated[EmailStr, StringConstraints(to_lower=True, max_length=320)]


class SubmittedAnswer(BaseModel):
    question_id: uuid.UUID
    choice_index: Annotated[int, Field(ge=0, le=3)]


class AssessmentSubmission(BaseModel):
    contributor: Annotated[
        ExistingContributorIdentity | NewContributorIdentity, Field(discriminator="kind")
    ]
    # One answer per question in the assessment.
    answers: Annotated[list[SubmittedAnswer], Field(min_length=1)]


class ConceptScore(BaseModel):
    concept: str
    correct: int
    total: int
    # correct / total * 100, rounded to two decimal places.
    score: float


class AssessmentSubmissionResponse(BaseModel):
    contributor_name: str
    scores: list[ConceptScore]



# --- Assessment results ------------------------------------------------------------------------


class ContributorConceptScore(BaseModel):
    concept: str
    # 0-100: the share of this concept's questions the contributor answered correctly.
    score: float


class ContributorResults(BaseModel):
    id: uuid.UUID
    name: str
    email: str
    # Mean of the per-concept scores.
    average_score: float
    # One entry per concept in the assessment, in the same order as `AssessmentResults.concepts`.
    scores: list[ContributorConceptScore]


class AssessmentResults(BaseModel):
    assessment: AssessmentResponse
    # The concepts the assessment covers, alphabetically.
    concepts: list[str]
    # Contributors who have taken this assessment, alphabetically.
    contributors: list[ContributorResults]
